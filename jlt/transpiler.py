"""
Transpiler: Compiles JLT (.jlt) AST into idiomatic, runnable Python 3 code.
"""

from typing import List, Optional, Tuple
from .ast_nodes import (
    ASTNode,
    Program,
    Stmt,
    Expr,
    LiteralExpr,
    VarExpr,
    UnaryExpr,
    BinaryExpr,
    LogicalExpr,
    CallExpr,
    ListLiteralExpr,
    DictLiteralExpr,
    IndexExpr,
    MemberExpr,
    AssignExpr,
    ExpressionStmt,
    VarDeclStmt,
    BlockStmt,
    PrintStmt,
    IfStmt,
    WhileStmt,
    ForEachStmt,
    CountFromStmt,
    FuncDefStmt,
    ReturnStmt,
    BreakStmt,
    ContinueStmt,
    TryCatchStmt,
)


class Transpiler:
    def __init__(self):
        self.indent_level = 0
        self.indent_str = "    "

    def transpile(self, program: Program) -> str:
        lines = [
            "# Generated by JLT (Just Like That) - Bangalorean English Compiler",
            "from jlt.builtins import *",
            "",
        ]
        for stmt in program.statements:
            code = self.stmt_to_code(stmt)
            if code:
                lines.append(code)
        return "\n".join(lines) + "\n"

    def indent(self) -> str:
        return self.indent_str * self.indent_level

    def stmt_to_code(self, stmt: Stmt) -> str:
        if isinstance(stmt, ExpressionStmt):
            return f"{self.indent()}{self.expr_to_code(stmt.expr)}"

        if isinstance(stmt, VarDeclStmt):
            val_code = self.expr_to_code(stmt.initializer) if stmt.initializer else "None"
            return f"{self.indent()}{stmt.name} = {val_code}"

        if isinstance(stmt, PrintStmt):
            args = ", ".join(self.expr_to_code(arg) for arg in stmt.args)
            return f"{self.indent()}tell_ra_macha({args})"

        if isinstance(stmt, IfStmt):
            cond = self.expr_to_code(stmt.condition)
            lines = [f"{self.indent()}if {cond}:"]
            lines.append(self.block_body_to_code(stmt.then_branch))

            for elif_cond, elif_branch in stmt.elif_branches:
                lines.append(f"{self.indent()}elif {self.expr_to_code(elif_cond)}:")
                lines.append(self.block_body_to_code(elif_branch))

            if stmt.else_branch:
                lines.append(f"{self.indent()}else:")
                lines.append(self.block_body_to_code(stmt.else_branch))

            return "\n".join(lines)

        if isinstance(stmt, WhileStmt):
            cond = self.expr_to_code(stmt.condition)
            lines = [f"{self.indent()}while {cond}:"]
            lines.append(self.block_body_to_code(stmt.body))
            return "\n".join(lines)

        if isinstance(stmt, ForEachStmt):
            iter_code = self.expr_to_code(stmt.iterable)
            lines = [f"{self.indent()}for {stmt.item_name} in {iter_code}:"]
            lines.append(self.block_body_to_code(stmt.body))
            return "\n".join(lines)

        if isinstance(stmt, CountFromStmt):
            start = self.expr_to_code(stmt.start_expr)
            to = self.expr_to_code(stmt.to_expr)
            step = self.expr_to_code(stmt.step_expr) if stmt.step_expr else "1"
            # Include upper bound (+ 1 for positive step)
            lines = [f"{self.indent()}for {stmt.var_name} in range({start}, ({to}) + (1 if ({step}) > 0 else -1), {step}):"]
            lines.append(self.block_body_to_code(stmt.body))
            return "\n".join(lines)

        if isinstance(stmt, FuncDefStmt):
            params = ", ".join(stmt.params)
            lines = [f"{self.indent()}def {stmt.name}({params}):"]
            lines.append(self.block_body_to_code(stmt.body))
            return "\n".join(lines)

        if isinstance(stmt, ReturnStmt):
            val = self.expr_to_code(stmt.value) if stmt.value else ""
            return f"{self.indent()}return {val}".rstrip() if val else f"{self.indent()}return"

        if isinstance(stmt, BreakStmt):
            return f"{self.indent()}break"

        if isinstance(stmt, ContinueStmt):
            return f"{self.indent()}continue"

        if isinstance(stmt, TryCatchStmt):
            lines = [f"{self.indent()}try:"]
            lines.append(self.block_body_to_code(stmt.try_block))
            if stmt.catch_block:
                err_var = stmt.error_name or "e"
                lines.append(f"{self.indent()}except Exception as {err_var}:")
                lines.append(self.block_body_to_code(stmt.catch_block))
            if stmt.finally_block:
                lines.append(f"{self.indent()}finally:")
                lines.append(self.block_body_to_code(stmt.finally_block))
            return "\n".join(lines)

        if isinstance(stmt, BlockStmt):
            return self.block_body_to_code(stmt)

        return f"{self.indent()}pass"

    def block_body_to_code(self, stmt: Stmt) -> str:
        self.indent_level += 1
        lines = []
        if isinstance(stmt, BlockStmt):
            if not stmt.statements:
                lines.append(f"{self.indent()}pass")
            else:
                for s in stmt.statements:
                    code = self.stmt_to_code(s)
                    if code:
                        lines.append(code)
        else:
            code = self.stmt_to_code(stmt)
            if code:
                lines.append(code)
            else:
                lines.append(f"{self.indent()}pass")
        self.indent_level -= 1
        return "\n".join(lines)

    def expr_to_code(self, expr: Expr) -> str:
        if isinstance(expr, LiteralExpr):
            if expr.value is None:
                return "None"
            return repr(expr.value)

        if isinstance(expr, VarExpr):
            return expr.name

        if isinstance(expr, UnaryExpr):
            op = expr.op
            if op in ("!", "opposite", "ulta", "not_only", "not"):
                op = "not "
            return f"({op}{self.expr_to_code(expr.right)})"

        if isinstance(expr, BinaryExpr):
            op = expr.op
            if op in ("same_to_same", "ditto"):
                op = "=="
            elif op in ("different_only", "not_same"):
                op = "!="
            elif op in ("more_than", "jaasti"):
                op = ">"
            elif op in ("less_than", "kammi"):
                op = "<"
            elif op in ("atleast", "jaasti_illa_equal"):
                op = ">="
            elif op in ("atmost", "kammi_illa_equal"):
                op = "<="
            elif op == "^":
                op = "**"
            return f"({self.expr_to_code(expr.left)} {op} {self.expr_to_code(expr.right)})"

        if isinstance(expr, LogicalExpr):
            op = "or" if expr.op in ("||", "or_else", "athava", "or") else "and"
            return f"({self.expr_to_code(expr.left)} {op} {self.expr_to_code(expr.right)})"

        if isinstance(expr, CallExpr):
            callee = self.expr_to_code(expr.callee)
            args = ", ".join(self.expr_to_code(a) for a in expr.args)
            return f"{callee}({args})"

        if isinstance(expr, ListLiteralExpr):
            items = ", ".join(self.expr_to_code(e) for e in expr.elements)
            return f"[{items}]"

        if isinstance(expr, DictLiteralExpr):
            pairs = ", ".join(f"{self.expr_to_code(k)}: {self.expr_to_code(v)}" for k, v in expr.pairs)
            return f"{{{pairs}}}"

        if isinstance(expr, IndexExpr):
            return f"{self.expr_to_code(expr.target)}[{self.expr_to_code(expr.index)}]"

        if isinstance(expr, MemberExpr):
            return f"{self.expr_to_code(expr.target)}.get('{expr.property_name}')"

        if isinstance(expr, AssignExpr):
            target = self.expr_to_code(expr.target)
            val = self.expr_to_code(expr.value)
            return f"{target} {expr.op} {val}"

        return "None"
